"""
Output Groundedness Guardrail for Naukri.com Domain Support Agent.
Verifies that generated responses are strictly substantiated by retrieved policy chunks,
rejecting hallucinated claims and triggering calibrated refusals.
"""

from typing import List, Tuple
import config
from rag.retrieval import FALLBACK_REFUSAL_MESSAGE


def verify_grounding(
    draft_answer: str,
    retrieved_chunks: List[str],
    similarity_score: float = 1.0,
    threshold: float = config.RAG_SIMILARITY_THRESHOLD,
) -> Tuple[bool, str]:
    """
    Validates output groundedness against retrieved context.
    
    Args:
        draft_answer: The candidate response generated by the agent.
        retrieved_chunks: List of retrieved policy text excerpts.
        similarity_score: Cosine similarity score of retrieval.
        threshold: Minimum acceptable threshold (default 0.60).
        
    Returns:
        Tuple of (is_grounded: bool, final_answer: str).
    """
    if not draft_answer or not draft_answer.strip():
        return False, FALLBACK_REFUSAL_MESSAGE

    # 1. Similarity threshold check
    if similarity_score < threshold:
        return False, FALLBACK_REFUSAL_MESSAGE

    # 2. Context presence check
    if not retrieved_chunks:
        # If no chunks were retrieved at all, cannot be grounded
        return False, FALLBACK_REFUSAL_MESSAGE

    combined_context = " ".join(retrieved_chunks).lower()
    draft_lower = draft_answer.lower()

    # If draft states refusal or lack of knowledge, accept refusal as valid
    if "i don't have information" in draft_lower or "not found" in draft_lower:
        return True, draft_answer

    # 3. Keyword grounding overlap check
    # Extract significant alphanumeric terms from draft (min 4 chars)
    words = [w for w in draft_lower.split() if len(w) >= 4 and w.isalnum()]
    if not words:
        return True, draft_answer

    matched_words = sum(1 for w in words if w in combined_context)
    overlap_ratio = matched_words / float(len(words))

    # Expect at least 35% token overlap with retrieved context for policy claims
    if overlap_ratio < 0.35:
        return False, FALLBACK_REFUSAL_MESSAGE

    return True, draft_answer


if __name__ == "__main__":
    context = [
        "The standard probation duration for all new hires is 6 months starting from joining.",
        "A formal 30-day performance review milestone is conducted between the employee and line manager.",
    ]
    
    grounded_draft = "Probation duration is 6 months with a 30-day performance review milestone."
    hallucinated_draft = "Employees get 18 months probation and free company cars with unlimited travel."
    
    print("=" * 70)
    print("Output Groundedness Guardrail Demonstration")
    print("=" * 70)
    
    is_g1, ans1 = verify_grounding(grounded_draft, context, similarity_score=0.82)
    print(f"Draft 1 (Grounded)    : \"{grounded_draft}\"")
    print(f"Verification Result   : Grounded={is_g1}")
    print(f"Final Answer          : \"{ans1}\"")
    print("-" * 70)
    
    is_g2, ans2 = verify_grounding(hallucinated_draft, context, similarity_score=0.35)
    print(f"Draft 2 (Hallucinated): \"{hallucinated_draft}\"")
    print(f"Verification Result   : Grounded={is_g2}")
    print(f"Final Answer          : \"{ans2}\"")
    print("=" * 70)
